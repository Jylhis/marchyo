// Renders a ConfigProfile + MarchyoOption catalogue into a Nix module string.
// Extracted from NixExportModal so it is unit-testable (generateNixConfig.test.js).

export function generateNixConfig(profile, options) {
  const enabledSet = new Set(profile.enabled_options || []);
  const customOptions = profile.options || {};
  const optionMap = Object.fromEntries((options || []).map((o) => [o.name, o]));

  const lines = [];
  lines.push(`# Generated by marchyo — profile: ${profile.name}`);
  lines.push(`# Platform: ${profile.platform}`);
  if (profile.description) lines.push(`# ${profile.description}`);
  lines.push("");
  lines.push(`{ config, pkgs, lib, ... }:`);
  lines.push("");
  lines.push("{");

  const namespaces = {};
  for (const optName of enabledSet) {
    const parts = optName.split(".");
    const ns = parts.length > 2 ? parts.slice(0, -1).join(".") : parts[0];
    if (!namespaces[ns]) namespaces[ns] = [];
    namespaces[ns].push(optName);
  }

  for (const [ns, opts] of Object.entries(namespaces)) {
    lines.push(`  # ${ns}`);
    for (const optName of opts) {
      const meta = optionMap[optName];
      const customVal = customOptions[optName];
      let val;
      if (customVal !== undefined) {
        val =
          typeof customVal === "boolean" ? String(customVal) : `"${customVal}"`;
      } else if (
        meta?.default_value !== undefined &&
        meta.default_value !== ""
      ) {
        val = meta.default_value;
      } else if (meta?.option_type === "bool") {
        val = "true";
      } else if (meta?.option_type === "int") {
        val = "0";
      } else if (
        meta?.option_type === "str" ||
        meta?.option_type === "string"
      ) {
        val = '""';
      } else if (meta?.option_type?.startsWith("list")) {
        val = "[ ]";
      } else {
        val = "true";
      }
      lines.push(`  ${optName} = ${val};`);
    }
    lines.push("");
  }

  // Custom option values not in enabled list
  for (const [key, val] of Object.entries(customOptions)) {
    if (!enabledSet.has(key)) {
      const v = typeof val === "boolean" ? String(val) : `"${val}"`;
      lines.push(`  ${key} = ${v};`);
    }
  }

  lines.push("}");
  return lines.join("\n");
}
