import { describe, expect, test } from "bun:test";
import { generateNixConfig } from "./generateNixConfig";

const CATALOGUE = [
  { name: "marchyo.desktop.enable", option_type: "bool", default_value: "" },
  { name: "marchyo.ai.model", option_type: "string", default_value: '"gpt"' },
  {
    name: "marchyo.users.extra",
    option_type: "list of string",
    default_value: "",
  },
  { name: "marchyo.performance.jobs", option_type: "int", default_value: "" },
];

const profile = (over = {}) => ({
  name: "workstation",
  platform: "nixos",
  enabled_options: [],
  options: {},
  ...over,
});

describe("generateNixConfig", () => {
  test("renders header, platform and module skeleton", () => {
    const out = generateNixConfig(
      profile({ description: "My box" }),
      CATALOGUE,
    );
    expect(out).toContain("# Generated by marchyo — profile: workstation");
    expect(out).toContain("# Platform: nixos");
    expect(out).toContain("# My box");
    expect(out).toContain("{ config, pkgs, lib, ... }:");
    expect(out.trim().endsWith("}")).toBe(true);
  });

  test("enabled options fall back per type when no default exists", () => {
    const out = generateNixConfig(
      profile({
        enabled_options: [
          "marchyo.desktop.enable",
          "marchyo.users.extra",
          "marchyo.performance.jobs",
        ],
      }),
      CATALOGUE,
    );
    expect(out).toContain("marchyo.desktop.enable = true;");
    expect(out).toContain("marchyo.users.extra = [ ];");
    expect(out).toContain("marchyo.performance.jobs = 0;");
  });

  test("catalogue default wins over the type fallback", () => {
    const out = generateNixConfig(
      profile({ enabled_options: ["marchyo.ai.model"] }),
      CATALOGUE,
    );
    expect(out).toContain('marchyo.ai.model = "gpt";');
  });

  test("custom values override defaults and render by JS type", () => {
    const out = generateNixConfig(
      profile({
        enabled_options: ["marchyo.ai.model", "marchyo.desktop.enable"],
        options: {
          "marchyo.ai.model": "claude",
          "marchyo.desktop.enable": false,
        },
      }),
      CATALOGUE,
    );
    expect(out).toContain('marchyo.ai.model = "claude";');
    expect(out).toContain("marchyo.desktop.enable = false;");
  });

  test("custom values outside the enabled set are still emitted", () => {
    const out = generateNixConfig(
      profile({ options: { "marchyo.theme.name": "sheet" } }),
      CATALOGUE,
    );
    expect(out).toContain('marchyo.theme.name = "sheet";');
  });

  test("options are grouped under a namespace comment", () => {
    const out = generateNixConfig(
      profile({ enabled_options: ["marchyo.desktop.enable"] }),
      CATALOGUE,
    );
    expect(out).toContain("# marchyo.desktop");
  });

  test("unknown option with no metadata defaults to true", () => {
    const out = generateNixConfig(
      profile({ enabled_options: ["marchyo.mystery.enable"] }),
      [],
    );
    expect(out).toContain("marchyo.mystery.enable = true;");
  });
});
